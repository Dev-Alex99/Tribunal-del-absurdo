export type RoomPhase = 
  | 'LOBBY' 
  | 'BRIEFING' 
  | 'WRITING' 
  | 'DELIBERATION' 
  | 'VERDICT' 
  | 'PODIUM';

export interface Player {
  id: string; // Socket ID or session ID
  name: string;
  avatarIndex: number;
  score: number;
  isHost: boolean;
  isAI?: boolean;
  isReady: boolean;
  hasSubmitted: boolean;
  currentPlea?: string;
  attachment?: string;
  reactions?: Record<string, number>;
  lastScoreGain?: number;
}

export interface CaseData {
  caseNumber: string; // e.g. "EXP-774-B"
  title: string;      // e.g. "El Sabotaje de la Máquina de Helados"
  plaintiff: string;  // e.g. "Don Jacinto, maestro heladero intolerante a la lactosa"
  description: string;
  requiredWords: string[]; // 3 required words
  rivalPlea?: string; // If in solo mode, generated by AI
}

export interface PlayerEvaluation {
  playerId: string;
  playerName: string;
  pleaText: string;
  attachment?: string;
  creativityScore: number; // 0-50
  audacityScore: number;   // 0-50
  requiredWordsUsed: string[];
  penalty: number;
  totalRoundScore: number;
  stamp: 'ABSUELTO_POR_GENIO' | 'CULPABLE_REINCIDENTE' | 'INDULTO_POR_PENA' | 'DESACATO_TOTAL' | 'LOCURA_TRANSITORIA';
  stampTitle: string;
  roast: string;
}

export interface VerdictData {
  evaluations: PlayerEvaluation[];
  roundWinnerId: string;
  roundWinnerName: string;
  magistrateCommentary: string;
}

export interface FinalPodiumData {
  winnerId: string;
  winnerName: string;
  honorificTitle: string;
  finalRankings: {
    playerId: string;
    playerName: string;
    totalScore: number;
    stampsReceived: string[];
  }[];
}

export interface RoomState {
  code: string;
  phase: RoomPhase;
  players: Player[];
  currentRound: number;
  totalRounds: number;
  currentCase: CaseData | null;
  timerEndsAt: number | null; // Unix timestamp ms for zero-latency drift
  latestVerdict: VerdictData | null;
  finalPodium: FinalPodiumData | null;
}
